#!/usr/bin/env node
/**
 * generate-compose-topology.js
 *
 * Generates docker-compose-local.yml for LOCAL (non-Swarm) experiments.
 * Reads an existing static topology JSON — never regenerates it.
 *
 * Usage:
 *   node generate-compose-topology.js [topology] [fault] [strategy] [seeds] [fault_base] [fault_partition] [project]
 *
 * Defaults:
 *   topology        = ring-50
 *   fault           = baseline-flaky
 *   strategy        = none
 *   seeds           = "1000,2000,3000,4000,5000"   (comma-separated; coordinator iterates with soft reset)
 *   fault_base      = no-wan                        (or wan-50ms)
 *   fault_partition = ""                            (or network-partition)
 *   project         = chaos                         (compose project namespace — lets parallel workers coexist)
 *
 * Output:
 *   docker-compose-local-<project>.yml  (bridge network, NET_ADMIN + NET_RAW)
 */

import { readFileSync, writeFileSync, mkdirSync } from 'fs';
import { resolve, dirname } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));

const TOPOLOGY = process.argv[2] || 'ring-50';
const FAULT = process.argv[3] || 'baseline-flaky';
const STRATEGY = process.argv[4] || 'none';
const SEEDS = process.argv[5] || '1000,2000,3000,4000,5000';
const FAULT_BASE = process.argv[6] || 'no-wan';
const FAULT_PARTITION = process.argv[7] || '';
const PROJECT = process.argv[8] || 'chaos';

const BASE_PORT = 4000;
const IMAGE = process.env.IMAGE || 'chaos-experiment:latest';

// Opcjonalny override katalogu wyników — pozwala uruchamiać eksperymenty
// "obok" oryginalnej macierzy bez nadpisywania results/. Puste = stare defaults.
const RESULTS_DIR_HOST = process.env.RESULTS_DIR_HOST || './results';
const RESULTS_DIR_CONTAINER = process.env.RESULTS_DIR_CONTAINER || '/results';

// Opcjonalne zmienne środowiskowe propagowane do serwisów (sensitivity / SWIM PoC).
// Jeśli nie ustawione, nie pojawiają się w compose — zachowane stare zachowanie.
const EXTRA_SVC_ENV = {};
if (process.env.STATIC_PARAMS) EXTRA_SVC_ENV.STATIC_PARAMS = process.env.STATIC_PARAMS;
if (process.env.SWIM_FANOUT) EXTRA_SVC_ENV.SWIM_FANOUT = process.env.SWIM_FANOUT;

// ── Load static topology ──────────────────────────────────────────────────────
const topoFile = resolve(__dirname, 'config', 'topologies', `${TOPOLOGY}.json`);
let topology;
try {
  topology = JSON.parse(readFileSync(topoFile, 'utf8'));
} catch (err) {
  console.error(`[generate] ERROR: cannot read topology file: ${topoFile}`);
  console.error(`           Available topologies are in when-gossip-goes-silent/config/topologies/`);
  process.exit(1);
}

// ── Compose generator ─────────────────────────────────────────────────────────
function generateDockerCompose(topology, fault, strategy, seeds, faultBase, faultPartition, project) {
  const netName = `chaos-net-${project}`;
  const lines = [
    `# docker-compose-local-${project}.yml — GENERATED by generate-compose-topology.js`,
    `# Topology: ${topology.name} | Strategy: ${strategy}`,
    `# Base: ${faultBase} | Overlay: ${fault} | Partition: ${faultPartition || '(none)'}`,
    `# Seeds: ${seeds}  (coordinator iterates within a single cluster via soft reset)`,
    `# Project: ${project}  (parallel workers use distinct project names to coexist)`,
    `# NixOS-safe: driver:bridge, NET_ADMIN+NET_RAW for tc netem and iptables`,
    ``,
    `services:`,
    ``,
  ];

  topology.services.forEach((svc, idx) => {
    const port = svc.port || (BASE_PORT + idx);
    const isGateway = svc.role === 'entry';
    const cpuRes = isGateway ? '0.05' : '0.02';
    const cpuLim = isGateway ? '0.25' : '0.20';
    const memRes = isGateway ? '32M' : '20M';
    const memLim = isGateway ? '256M' : '128M';

    lines.push(`  ${svc.id}:`);
    lines.push(`    image: ${IMAGE}`);
    lines.push(`    command: ["node", "runner/service-runner.js"]`);
    lines.push(`    restart: "on-failure"`);
    lines.push(`    environment:`);
    lines.push(`      SERVICE_ID: "${svc.id}"`);
    lines.push(`      TOPOLOGY: "${topology.name}"`);
    // Services use the overlay fault name for local fault-state routing.
    // Base/partition are handled centrally by the coordinator.
    lines.push(`      FAULT_PROFILE: "${fault}"`);
    lines.push(`      STRATEGY: "${strategy}"`);
    // Seed here is the first seed in the cell; services get re-seeded via
    // POST /experiment/reset between iterations (soft reset protocol).
    lines.push(`      SEED: "${seeds.split(',')[0].trim()}"`);
    lines.push(`      BASE_PORT: "${BASE_PORT}"`);
    for (const [k, v] of Object.entries(EXTRA_SVC_ENV)) {
      // Cudzysłów podwójny + escape — STATIC_PARAMS zawiera JSON z cudzysłowami.
      const escaped = String(v).replace(/"/g, '\\"');
      lines.push(`      ${k}: "${escaped}"`);
    }
    lines.push(`    networks:`);
    lines.push(`      - ${netName}`);
    lines.push(`    volumes:`);
    lines.push(`      - ./config:/app/config:ro`);
    lines.push(`    cap_add:`);
    lines.push(`      - NET_ADMIN`);
    lines.push(`      - NET_RAW`);
    lines.push(`    deploy:`);
    lines.push(`      resources:`);
    lines.push(`        reservations:`);
    lines.push(`          cpus: '${cpuRes}'`);
    lines.push(`          memory: ${memRes}`);
    lines.push(`        limits:`);
    lines.push(`          cpus: '${cpuLim}'`);
    lines.push(`          memory: ${memLim}`);
    lines.push(`    healthcheck:`);
    lines.push(`      test: ["CMD", "node", "-e", "fetch('http://localhost:${port}/health').then(r=>r.ok?process.exit(0):process.exit(1)).catch(()=>process.exit(1))"]`);
    lines.push(`      interval: 10s`);
    lines.push(`      timeout: 5s`);
    lines.push(`      retries: 12`);
    lines.push(`      start_period: 20s`);
    lines.push(`    `);  // intentional blank service separator in YAML
  });

  lines.push(`  coordinator:`);
  lines.push(`    image: ${IMAGE}`);
  lines.push(`    command: ["node", "runner/coordinator.js"]`);
  lines.push(`    restart: "no"`);
  lines.push(`    environment:`);
  lines.push(`      TOPOLOGY: "${topology.name}"`);
  lines.push(`      FAULT_BASE: "${faultBase}"`);
  lines.push(`      FAULT_PROFILE: "${fault}"`);
  lines.push(`      FAULT_PARTITION: "${faultPartition}"`);
  lines.push(`      STRATEGY: "${strategy}"`);
  lines.push(`      SEEDS: "${seeds}"`);
  lines.push(`      BASE_PORT: "${BASE_PORT}"`);
  // RPS=20; measurement shortened to 60s (from 90s in original matrix) — the
  // fault overlays complete within 60s of measurement, so the extra 30s of
  // original window was post-fault tail with no additional signal.
  // WARMUP unchanged at 15s to absorb JIT and CB init.
  lines.push(`      RPS: "20"`);
  lines.push(`      DURATION_SEC: "60"`);
  lines.push(`      WARMUP_SEC: "15"`);
  lines.push(`      RESULTS_DIR: ${RESULTS_DIR_CONTAINER}`);
  lines.push(`      HEALTH_TIMEOUT_MS: "300000"`);
  lines.push(`      INTER_SEED_SETTLE_MS: "2000"`);
  // SPOF test hook for Central strategy (kills coordinator mid-run). 0 = disabled.
  if (process.env.SPOF_KILL_AT_SEC) {
    lines.push(`      SPOF_KILL_AT_SEC: "${process.env.SPOF_KILL_AT_SEC}"`);
  }
  lines.push(`    cap_add:`);
  lines.push(`      - NET_ADMIN`);
  lines.push(`      - NET_RAW`);
  lines.push(`    volumes:`);
  lines.push(`      - ./config:/app/config:ro`);
  lines.push(`      - ${RESULTS_DIR_HOST}:${RESULTS_DIR_CONTAINER}`);
  lines.push(`    networks:`);
  lines.push(`      - ${netName}`);
  lines.push(`    depends_on:`);

  topology.services.forEach((svc) => {
    lines.push(`      ${svc.id}:`);
    lines.push(`        condition: service_started`);
  });

  lines.push(``);
  lines.push(`networks:`);
  lines.push(`  ${netName}:`);
  lines.push(`    driver: bridge`);
  lines.push(``);

  return lines.join('\n');
}

// ── Write output ──────────────────────────────────────────────────────────────
// Utworzenie katalogu host-side (tworzy tylko lokalny folder, nie dotyka wolumenów).
mkdirSync(RESULTS_DIR_HOST.replace(/^\.\//, ''), { recursive: true });

const compose = generateDockerCompose(topology, FAULT, STRATEGY, SEEDS, FAULT_BASE, FAULT_PARTITION, PROJECT);
const outFile = `docker-compose-local-${PROJECT}.yml`;
writeFileSync(outFile, compose);

console.log(
  `[generate] ${outFile}` +
  `  (topology=${TOPOLOGY} strategy=${STRATEGY} base=${FAULT_BASE} fault=${FAULT} partition=${FAULT_PARTITION || '(none)'} seeds=${SEEDS})`
);
