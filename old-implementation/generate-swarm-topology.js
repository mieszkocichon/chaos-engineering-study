#!/usr/bin/env node

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));


const args = process.argv.slice(2);
const NUM_SERVICES  = parseInt(args[0], 10) || 20;
const FAULT_PROFILE = args[1] || 'cascade-crash';
const STRATEGY      = args[2] || 'mas-agent';


const SEED          = args[3] || '42';
const OUTPUT_FILE   = path.join(__dirname, 'docker-compose-swarm.yml');

const TOPOLOGY_NAME = `ring-${NUM_SERVICES}`;
console.log(`Generating SWARM configuration for ${NUM_SERVICES} services in RING topology...`);

let content = `# AUTOMATICALLY GENERATED BY generate-swarm-topology.js
# Topology: RING (${NUM_SERVICES} nodes) - SWARM MODE

version: '3.8'

x-common-env: &common-env
  TOPOLOGY: ${TOPOLOGY_NAME}
  FAULT_PROFILE: ${FAULT_PROFILE}
  STRATEGY: ${STRATEGY}
  SEED: "${SEED}"
  BASE_PORT: "4000"

# Volume mount: we mount when-gossip-goes-silent/config to /app/config in each container.
# This makes dynamically generated topology files (ring-N.json) visible
# without rebuilding the Docker image after each experiment iteration.
x-config-volume: &config-volume
  - ./config:/app/config:ro

services:

  gateway:
    image: chaos-experiment:latest
    environment:
      <<: *common-env
      SERVICE_ID: gateway
      DOWNSTREAM_SERVICES: "${generateServiceList(NUM_SERVICES)}"
    volumes: *config-volume
    ports:
      - "4000:4000"
    networks:
      - chaos-net
    cap_add:
      - NET_ADMIN
    deploy:
      replicas: 1
      restart_policy:
        condition: on-failure
      resources:
        reservations:
          cpus: '0.05'
          memory: 32M
        limits:
          cpus: '0.25'
          memory: 256M
    healthcheck:
      test: ["CMD", "node", "-e", "fetch('http://localhost:4000/health').then(r => {if(!r.ok) process.exit(1)}).catch(() => process.exit(1))"]
      interval: 10s
      timeout: 5s
      retries: 10
      start_period: 30s

`;


const serviceNames = [];

for (let i = 1; i <= NUM_SERVICES; i++) {
  const id = i.toString().padStart(2, '0');
  const svcName = `svc-${id}`;
  serviceNames.push(svcName);


  const prevId = (i === 1 ? NUM_SERVICES : i - 1).toString().padStart(2, '0');
  const nextId = (i === NUM_SERVICES ? 1 : i + 1).toString().padStart(2, '0');
  const neighbors = `svc-${prevId},svc-${nextId}`;
  const port = 4000 + i;

  content += `  ${svcName}:
    image: chaos-experiment:latest
    environment:
      <<: *common-env
      SERVICE_ID: ${svcName}
      STRATEGY_NAME: ${STRATEGY} # Pass strategy name to generic-service
      GOSSIP_PEERS: "${neighbors}"
      PORT: "${port}"
    volumes: *config-volume
    networks:
      - chaos-net
    # REQUIRED FOR REAL NETWORK FAULTS (tc, netem)
    cap_add:
      - NET_ADMIN
    deploy:
      replicas: 1
      restart_policy:
        condition: on-failure
      resources:
        reservations:
          cpus: '0.02'
          memory: 20M
        limits:
          cpus: '0.2'
          memory: 128M
    healthcheck:
      test: ["CMD", "node", "-e", "fetch('http://localhost:${port}/health').then(r => {if(!r.ok) process.exit(1)}).catch(() => process.exit(1))"]
      interval: 10s
      timeout: 5s
      retries: 10
      start_period: 20s


`;
}


content += `  coordinator:
    image: chaos-experiment:latest
    command: ["node", "runner/coordinator.js"]
    environment:
      <<: *common-env
      RPS: "20"
      DURATION_SEC: "90"
      WARMUP_SEC: "15"
      RESULTS_DIR: /results
      HEALTH_TIMEOUT_MS: "300000"
      EXPECTED_SERVICES: "${serviceNames.join(',')}"
    volumes:
      - ./results:/results
      - ./config:/app/config:ro
    networks:
      - chaos-net
    cap_add:
      - NET_ADMIN
    deploy:
      replicas: 1
      restart_policy:
        condition: none
`;

content += `
networks:
  chaos-net:
    driver: overlay
    attachable: true
`;

function generateServiceList(n) {
  const list = [];
  for (let i = 1; i <= n; i++) {
    list.push(`svc-${i.toString().padStart(2, '0')}`);
  }
  return list.join(',');
}


const topologyJson = {
  name: TOPOLOGY_NAME,
  description: `Ring topology with ${NUM_SERVICES} nodes (Swarm)`,
  services: [],
  edges: []
};


topologyJson.services.push({ id: 'gateway', role: 'entry' });


for (let i = 1; i <= NUM_SERVICES; i++) {
  const id = i.toString().padStart(2, '0');
  const svcId = `svc-${id}`;
  topologyJson.services.push({ id: svcId, role: 'service', port: 4000 + i });

  
  topologyJson.edges.push({ from: 'gateway', to: svcId });


  const nextNum = i === NUM_SERVICES ? 1 : i + 1;
  const nextId = `svc-${nextNum.toString().padStart(2, '0')}`;
  topologyJson.edges.push({ from: svcId, to: nextId, kind: 'gossip' });
}


const topologyFile = path.join(__dirname, 'when-gossip-goes-silent', 'config', 'topologies', `${TOPOLOGY_NAME}.json`);
fs.mkdirSync(path.dirname(topologyFile), { recursive: true });
fs.writeFileSync(topologyFile, JSON.stringify(topologyJson, null, 2));
console.log(`[generate] ${topologyFile}`);

fs.writeFileSync(OUTPUT_FILE, content);
console.log(`Done! File saved to: ${OUTPUT_FILE}`);