#!/usr/bin/env node

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));


const NUM_SERVICES = 20;
const OUTPUT_FILE = path.join(__dirname, 'docker-compose-scale.yml');

console.log(`Generating configuration for ${NUM_SERVICES} services in RING topology...`);

let content = `# Generated by generate-ring-topology.js
# Topology: ring (${NUM_SERVICES} nodes)

name: chaos-scale-ring

x-service: &service-base
  build:
    context: .
    dockerfile: Dockerfile
  image: chaos-experiment:latest
  command: ["node", "runner/service-runner.js"]
  networks:
    - chaos-net
  deploy:
    resources:
      limits:
        cpus: '0.15'    # CPU limit
        memory: 128M

x-common-env: &common-env
  TOPOLOGY: ring-20
  FAULT_PROFILE: cascade-crash
  STRATEGY: mas-agent
  SEED: "42"
  BASE_PORT: "4000"

services:

  gateway:
    <<: *service-base
    environment:
      <<: *common-env
      SERVICE_ID: gateway
      # Gateway knows all nodes to distribute traffic (Load Balancing)
      DOWNSTREAM_SERVICES: "${generateServiceList(NUM_SERVICES)}"
    ports:
      - "4000:4000"
    healthcheck:
      test: ["CMD", "wget", "-q", "http://localhost:4000/health", "-O", "/dev/null"]
      interval: 10s
      timeout: 5s
      retries: 10
      start_period: 30s

`;


const serviceNames = [];

for (let i = 1; i <= NUM_SERVICES; i++) {
  const id = i.toString().padStart(2, '0'); 
  const svcName = `svc-${id}`;
  serviceNames.push(svcName);
  const port = 4000 + i;


  const prevId = (i === 1 ? NUM_SERVICES : i - 1).toString().padStart(2, '0');
  const nextId = (i === NUM_SERVICES ? 1 : i + 1).toString().padStart(2, '0');
  
  const neighbors = `svc-${prevId},svc-${nextId}`;

  content += `  ${svcName}:
    <<: *service-base
    environment:
      <<: *common-env
      SERVICE_ID: ${svcName}
      GOSSIP_PEERS: "${neighbors}"
    ports:
      - "${port}:${port}"

`;
}


content += `  coordinator:
    image: chaos-experiment:latest
    command: ["node", "runner/coordinator.js"]
    environment:
      <<: *common-env
      RPS: "20"            # Increased RPS for larger scale
      DURATION_SEC: "90"   # Longer duration to observe ring propagation
      WARMUP_SEC: "15"
      RESULTS_DIR: /results
      HEALTH_TIMEOUT_MS: "300000" # 5 minutes for 20 containers to start
      EXPECTED_SERVICES: "${serviceNames.join(',')}"
    volumes:
      - ./results:/results
    networks:
      - chaos-net
    depends_on:
      gateway:
        condition: service_healthy
`;


content += `
networks:
  chaos-net:
    driver: bridge
`;

function generateServiceList(n) {
  const list = [];
  for (let i = 1; i <= n; i++) {
    list.push(`svc-${i.toString().padStart(2, '0')}`);
  }
  return list.join(',');
}

fs.writeFileSync(OUTPUT_FILE, content);
console.log(`Done! File saved to: ${OUTPUT_FILE}`);