/// `generate-compose-topology.js` → content of `docker-compose-local-<project>.yml`.
pub fn compose(topology: &Value, o: &ComposeOpts) -> String {
    let config_mount = o.config_dir_host.as_deref().unwrap_or("./config");
    let net = format!("chaos-net-{}", o.project);
    let name = js_str(&topology["name"]);
    let mut l: Vec<String> = vec![
        format!("# docker-compose-local-{}.yml — GENERATED by generate-compose-topology.js", o.project),
        format!("# Topology: {name} | Strategy: {}", o.strategy),
        format!(
            "# Base: {} | Overlay: {} | Partition: {}",
            o.fault_base,
            o.fault,
            if o.fault_partition.is_empty() { "(none)" } else { o.fault_partition }
        ),
        format!("# Seeds: {}  (coordinator iterates within a single cluster via soft reset)", o.seeds),
        format!("# Project: {}  (parallel workers use distinct project names to coexist)", o.project),
        "# NixOS-safe: driver:bridge, NET_ADMIN+NET_RAW for tc netem and iptables".into(),
        String::new(),
        "services:".into(),
        String::new(),
    ];
    let mut extra: Vec<(&str, &String)> = vec![];
    if let Some(v) = &o.static_params {
        extra.push(("STATIC_PARAMS", v));
    }
    if let Some(v) = &o.swim_fanout {
        extra.push(("SWIM_FANOUT", v));
    }
    let first_seed = o.seeds.split(',').next().unwrap_or("").trim();
    let svcs = topology["services"].as_array().unwrap();
    for (idx, svc) in svcs.iter().enumerate() {
        let id = js_str(&svc["id"]);
        // `svc.port || (BASE_PORT + idx)` – only used for the healthcheck URL
        let port = svc.get("port").filter(|p| crate::topology::truthy(p)).map_or((BASE_PORT + idx as u32).to_string(), js_str);
        let gw = svc["role"] == "entry";
        let gw_lim = o.gateway_cpus.as_deref().unwrap_or("0.25");
        let (cpu_res, cpu_lim, mem_res, mem_lim) = if gw { ("0.05", gw_lim, "32M", "256M") } else { ("0.02", "0.20", "20M", "128M") };
        l.extend([
            format!("  {id}:"),
            format!("    image: {}", o.image),
            format!("    command: {SVC_CMD}"),
            "    restart: \"on-failure\"".into(),
            "    environment:".into(),
            format!("      SERVICE_ID: \"{id}\""),
            format!("      TOPOLOGY: \"{name}\""),
            format!("      FAULT_PROFILE: \"{}\"", o.fault),
            format!("      STRATEGY: \"{}\"", o.strategy),
            format!("      SEED: \"{first_seed}\""),
            format!("      BASE_PORT: \"{BASE_PORT}\""),
        ]);
        for (k, v) in &extra {
            l.push(format!("      {k}: \"{}\"", v.replace('"', "\\\"")));
        }
        if let Some(extra_env) = &o.extra_env {
            for (k, v) in extra_env {
                l.push(format!("      {k}: \"{}\"", v.replace('"', "\\\"")));
            }
        }
        l.extend([
            "    networks:".into(),
            format!("      - {net}"),
            "    volumes:".into(),
            format!("      - {config_mount}:/app/config:ro"),
            "    cap_add:".into(),
            "      - NET_ADMIN".into(),
            "      - NET_RAW".into(),
            "    deploy:".into(),
            "      resources:".into(),
            "        reservations:".into(),
            format!("          cpus: '{cpu_res}'"),
            format!("          memory: {mem_res}"),
            "        limits:".into(),
            format!("          cpus: '{cpu_lim}'"),
            format!("          memory: {mem_lim}"),
            "    healthcheck:".into(),
            format!("      test: {}", curl_health(&port)),
            "      interval: 10s".into(),
            "      timeout: 5s".into(),
            "      retries: 12".into(),
            "      start_period: 20s".into(),
            "    ".into(),
        ]);
    }
    l.extend([
        "  coordinator:".into(),
        format!("    image: {}", o.image),
        format!("    command: {COORD_CMD}"),
        "    restart: \"no\"".into(),
        "    environment:".into(),
        format!("      TOPOLOGY: \"{name}\""),
        format!("      FAULT_BASE: \"{}\"", o.fault_base),
        format!("      FAULT_PROFILE: \"{}\"", o.fault),
        format!("      FAULT_PARTITION: \"{}\"", o.fault_partition),
        format!("      STRATEGY: \"{}\"", o.strategy),
        format!("      SEEDS: \"{}\"", o.seeds),
        format!("      BASE_PORT: \"{BASE_PORT}\""),
        format!("      RPS: \"{}\"", o.rps.unwrap_or(20)),
        format!("      DURATION_SEC: \"{}\"", o.duration_sec.unwrap_or(60)),
        format!("      WARMUP_SEC: \"{}\"", o.warmup_sec.unwrap_or(15)),
        format!("      RESULTS_DIR: {}", o.results_dir_container),
        "      HEALTH_TIMEOUT_MS: \"300000\"".into(),
        "      INTER_SEED_SETTLE_MS: \"2000\"".into(),
    ]);
    if let Some(v) = &o.spof_kill_at_sec {
        l.push(format!("      SPOF_KILL_AT_SEC: \"{v}\""));
    }
    l.extend([
        "    cap_add:".into(),
        "      - NET_ADMIN".into(),
        "      - NET_RAW".into(),
        "    volumes:".into(),
        format!("      - {config_mount}:/app/config:ro"),
        format!("      - {}:{}", o.results_dir_host, o.results_dir_container),
        "    networks:".into(),
        format!("      - {net}"),
        "    depends_on:".into(),
    ]);
    for svc in svcs {
        l.push(format!("      {}:", js_str(&svc["id"])));
        l.push("        condition: service_started".into());
    }
    let driver = o.network_driver.as_deref().unwrap_or("bridge");
    l.extend([String::new(), "networks:".into(), format!("  {net}:"), format!("    driver: {driver}"), String::new()]);
    l.join("\n")
}

/// `${value}` of a JSON value, like a JS template literal.
fn js_str(v: &Value) -> String {
    match v {
        Value::String(s) => s.clone(),
        Value::Number(n) => metastable::js::js_number(n.as_f64().unwrap()),
        Value::Null => "null".into(),
        other => other.to_string(),
    }
}

