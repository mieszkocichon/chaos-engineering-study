/// `scripts/generate-mesh-topology.js`: N services, K random gossip peers each (mulberry32).
pub fn mesh(n: u32, k: u32, seed: f64) -> Result<Value, String> {
    if n < 2 || k < 1 || k >= n {
        return Err(format!("Bad parameters: N={n} K={k} (require N>=2, 1<=K<N)"));
    }
    let mut rand = mulberry32(seed);
    let id = |i: u32| format!("svc-{i:02}");
    let mut services = vec![json!({ "id": "gateway", "role": "entry" })];
    for i in 1..=n {
        services.push(json!({ "id": id(i), "role": "service", "port": 4000 + i }));
    }
    let mut edges: Vec<Value> = (1..=n).map(|i| json!({ "from": "gateway", "to": id(i) })).collect();
    let all: Vec<String> = (1..=n).map(id).collect();
    for src in &all {
        let mut pool: Vec<&String> = all.iter().filter(|x| *x != src).collect();
        for _ in 0..k {
            if pool.is_empty() {
                break;
            }
            let dst = pool.remove((rand() * pool.len() as f64).floor() as usize);
            edges.push(json!({ "from": src, "to": dst, "kind": "gossip" }));
        }
    }
    Ok(json!({
        "name": format!("mesh-{n}"),
        "description": format!("Mesh gossip topology: N={n} services, K={k} random peers each (seed={}).", metastable::js::js_number(seed)),
        "services": services,
        "edges": edges,
    }))
}

