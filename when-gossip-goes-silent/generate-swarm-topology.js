#!/usr/bin/env node

import { writeFileSync, mkdirSync } from 'fs';

const SCALE = parseInt(process.argv[2] || '20', 10);
const FAULT = process.argv[3] || 'baseline-flaky';
const STRATEGY = process.argv[4] || 'none';
const SEED = process.argv[5] || '42';

const BASE_PORT = 4000;
const IMAGE = process.env.REGISTRY
  ? `${process.env.REGISTRY}/chaos-experiment:latest`
  : 'chaos-experiment:latest';


function generateTopology(n) {
  if (n < 5) throw new Error('SCALE must be at least 5 (1 gateway + 4 tier-1 nodes)');

  const TIER1_IDS = ['svc-a', 'svc-b', 'svc-c', 'svc-d'];
  const t1Count = 4;
  const t2Count = n - 1 - t1Count;

  const services = [{ id: 'gateway', role: 'entry' }];
  const edges = [];

  for (const id of TIER1_IDS) {
    services.push({ id });
    edges.push({ from: 'gateway', to: id });
  }

  for (let i = 1; i <= t2Count; i++) {
    const id = `svc-${i}`;
    const parent = TIER1_IDS[(i - 1) % t1Count];
    services.push({ id });
    edges.push({ from: parent, to: id });
  }

  return {
    name: `scale-${n}`,
    description:
      `${n}-node layered topology: 1 gateway + 4 mid-tier (svc-a/b/c/d) + ${t2Count} leaf nodes. ` +
      `Designed for gossip protocol evaluation at scale (N≥20).`,
    defaults: {
      processingDelayMs: { distribution: 'normal', mean: 20, std: 5 },
    },
    services,
    edges,
  };
}


function generateDockerCompose(topology, fault, strategy) {
  const lines = [
    `# docker-compose-swarm.yml — GENERATED by generate-swarm-topology.js`,
    `# Topology: ${topology.name} | Fault: ${fault} | Strategy: ${strategy}`,
    `# Regenerate: node generate-swarm-topology.js ${SCALE} ${fault} ${strategy}`,
    ``,
    `version: "3.9"`,
    ``,
    `services:`,
    ``,
  ];

  topology.services.forEach((svc) => {
    lines.push(`  ${svc.id}:`);
    lines.push(`    image: ${IMAGE}`);
    lines.push(`    command: ["node", "runner/service-runner.js"]`);
    lines.push(`    environment:`);
    lines.push(`      SERVICE_ID: ${svc.id}`);
    lines.push(`      TOPOLOGY: ${topology.name}`);
    lines.push(`      FAULT_PROFILE: ${fault}`);
    lines.push(`      STRATEGY: ${strategy}`);
    lines.push(`      SEED: "${SEED}"`);
    lines.push(`      BASE_PORT: "${BASE_PORT}"`);
    lines.push(`    networks:`);
    lines.push(`      - chaos-overlay`);
    lines.push(`    volumes:`);
    lines.push(`      - ./config:/app/config:ro`);
    lines.push(`    cap_add:`);
    lines.push(`      - NET_ADMIN`);
    lines.push(`      - NET_RAW`);
    lines.push(`    healthcheck:`);
    lines.push(`      test: ["CMD", "node", "-e", "fetch('http://localhost:${BASE_PORT + topology.services.indexOf(svc)}/health').then(r=>r.ok?process.exit(0):process.exit(1)).catch(()=>process.exit(1))"]`);
    lines.push(`      interval: 10s`);
    lines.push(`      timeout: 5s`);
    lines.push(`      retries: 10`);
    lines.push(`      start_period: 20s`);
    lines.push(`    deploy:`);
    lines.push(`      replicas: 1`);
    lines.push(`      resources:`);
    lines.push(`        reservations:`);
    lines.push(`          cpus: '0.02'`);
    lines.push(`          memory: 20M`);
    lines.push(`        limits:`);
    lines.push(`          cpus: '0.20'`);
    lines.push(`          memory: 128M`);
    lines.push(`      restart_policy:`);
    lines.push(`        condition: on-failure`);
    lines.push(`        delay: 5s`);
    lines.push(`        max_attempts: 5`);
    lines.push(``);
  });

  lines.push(`  coordinator:`);
  lines.push(`    image: ${IMAGE}`);
  lines.push(`    command: ["node", "runner/coordinator.js"]`);
  lines.push(`    environment:`);
  lines.push(`      TOPOLOGY: ${topology.name}`);
  lines.push(`      FAULT_PROFILE: ${fault}`);
  lines.push(`      STRATEGY: ${strategy}`);
  lines.push(`      SEED: "42"`);
  lines.push(`      BASE_PORT: "${BASE_PORT}"`);
  lines.push(`      RPS: "50"`);
  lines.push(`      DURATION_SEC: "60"`);
  lines.push(`      WARMUP_SEC: "10"`);
  lines.push(`      RESULTS_DIR: /results`);
  lines.push(`      HEALTH_TIMEOUT_MS: "540000"`);
  lines.push(`    volumes:`);
  lines.push(`      - ./config:/app/config:ro`);
  lines.push(`      - ./results:/results`);
  lines.push(`    networks:`);
  lines.push(`      - chaos-overlay`);
  lines.push(`    depends_on:`);
  topology.services.forEach((svc) => {
    lines.push(`      ${svc.id}:`);
    lines.push(`        condition: service_started`);
  });
  lines.push(`    deploy:`);
  lines.push(`      replicas: 1`);
  lines.push(`      restart_policy:`);
  lines.push(`        condition: none`);
  lines.push(``);

  lines.push(`networks:`);
  lines.push(`  chaos-overlay:`);
  lines.push(`    driver: overlay`);
  lines.push(`    attachable: true`);
  lines.push(``);

  return lines.join('\n');
}


const topology = generateTopology(SCALE);

mkdirSync('config/topologies', { recursive: true });
const topoPath = `config/topologies/${topology.name}.json`;
writeFileSync(topoPath, JSON.stringify(topology, null, 2));
console.log(`[generate] ${topoPath}  (${topology.services.length} services, ${topology.edges.length} edges)`);

const compose = generateDockerCompose(topology, FAULT, STRATEGY);
writeFileSync('docker-compose-swarm.yml', compose);
console.log(`[generate] docker-compose-swarm.yml  (fault=${FAULT} strategy=${STRATEGY})`);
